"""report.py — build the PDF paper from reports/paper/paper.md with Pandoc + XeLaTeX (MiKTeX).

Global context: the paper is written in Markdown (reviewable on GitHub) and compiled to PDF here.
XeLaTeX is used for Unicode text; Cambria/Cambria Math are Windows system fonts that cover the
symbols used. Pandoc manual: https://pandoc.org/MANUAL.html#creating-a-pdf
"""

import json
import subprocess

from steering_explainer.config import Settings
from steering_explainer.log import get_logger

log = get_logger(__name__)


def _fmt(m: float, lo: float, hi: float, nd: int = 3) -> str:
    return f"{m:+.{nd}f} [{lo:+.{nd}f}, {hi:+.{nd}f}]"


def _tables(name: str, st: dict, ph: dict) -> list[str]:
    """Markdown tables of one experiment's summary.json (+ post-hoc lexical rates)."""
    pr, h2, h3 = st["primary"], st["h2_spearman"], st["h3_sign"]
    conds = sorted(st["means"]["p_pos"], key=lambda k: (k.startswith("random"), float(k.split("_")[1])))
    L = [f"## {name} (N = {st['n_prompts']} prompts, {st['n_completions']} completions)", "",
         "| Condition | P(positive) mean [95% CI] | NLL nats/token [95% CI] | ΔNLL vs α=0 [95% CI] | 'lov…' share | 'hate' share |",
         "|---|---|---|---|---|---|"]
    for c in conds:
        p, n = st["means"]["p_pos"][c], st["means"]["nll"][c]
        d = st["fluency"].get(c)
        r = ph["rates"][c]
        L.append(f"| {c} | {p[0]:.3f} [{p[1]:.3f}, {p[2]:.3f}] | {n[0]:.3f} [{n[1]:.3f}, {n[2]:.3f}] | "
                 f"{_fmt(d['mean'], d['lo'], d['hi']) if d else '—'} | {r['love'][0]:.3f} | {r['hate'][0]:.3f} |")
    L += ["", "| Test | Estimate [95% CI] | p (Wilcoxon) | p (Holm) | Verdict |", "|---|---|---|---|---|",
          f"| Primary: {pr['contrast']} (d_z = {pr['dz']:.3f}) | {_fmt(pr['mean'], pr['lo'], pr['hi'])} | — | — | {pr['verdict']} |",
          f"| H2: mean per-prompt Spearman ρ(α, P_pos) | {_fmt(h2['mean_rho'], h2['lo'], h2['hi'])} | — | — | {h2['verdict']} |",
          f"| H3: steer(−5) − steer(0) | {_fmt(h3['mean'], h3['lo'], h3['hi'])} | {h3['p_raw']:.2g} | {h3['p_holm']:.2g} | {h3['verdict']} |"]
    L += [f"| secondary: {t['contrast']} | {_fmt(t['mean'], t['lo'], t['hi'])} | {t['p_raw']:.2g} | {t['p_holm']:.2g} | — |"
          for t in st["secondary"] if not t["contrast"].startswith("steer_-")]
    L += ["", "Primary contrast per seed: " + "; ".join(f"seed {k}: {_fmt(v['mean'], v['lo'], v['hi'])}"
                                                      for k, v in st["primary_per_seed"].items()), ""]
    return L


def write_results_tables(s: Settings) -> None:
    """reports/results_tables.md — generated from data/study/*.json; reports cite it instead of retyping numbers."""
    d = s.data_dir / "study"
    load = lambda f: json.loads((d / f).read_text(encoding="utf-8"))
    power = load("power.json")
    out = ["# Results tables (generated by `uv run steering-explainer --phases tables`; do not edit by hand)", "",
           f"Pilot (N = {power['pilot_n']}): mean steer(5) − random(5) = {power['pilot_mean_diff']:+.3f}, d_z = "
           f"{power['pilot_dz']:.3f}, required N for 80% power = {power['required_n_80pct']}, chosen N = {power['chosen_n']}.",
           "'lov…'/'hate' shares are post-hoc (exploratory, not pre-registered): fraction of completions matching "
           "`lov` / `hat(e|ing|red)`, averaged per prompt.", ""]
    out += _tables("Experiment 01", load("summary.json"), load("main_posthoc.json"))
    out += _tables("Experiment 02 (powered replication)", load("exp02_summary.json"), load("exp02_posthoc.json"))
    (s.reports_dir / "results_tables.md").write_text("\n".join(out), encoding="utf-8")


def build_paper(s: Settings) -> None:
    src = s.reports_dir / "paper" / "paper.md"
    pdf = src.with_suffix(".pdf")
    cmd = ["pandoc", str(src), "-o", str(pdf), "--pdf-engine=xelatex", "--resource-path", str(s.reports_dir),
           "-V", "mainfont=Cambria", "-V", "mathfont=Cambria Math", "-V", "geometry:margin=2.2cm",
           "-V", "colorlinks=true", "--number-sections"]
    log.info("$ %s", " ".join(cmd))
    out = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", errors="replace")
    for line in (out.stdout + out.stderr).splitlines():
        if line.strip() and "major issue" not in line:  # MiKTeX's "check for updates" nag is noise
            log.info("  %s", line)
    if out.returncode != 0:
        raise RuntimeError(f"pandoc failed ({out.returncode})")
    log.info("Paper written to %s", pdf)
